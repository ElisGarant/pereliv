"""Стартовые данные: бесплатные уроки, модули, урок 7 с тестом, пара заказов.
Запуск: python -m app.seed  (повторный запуск ничего не дублирует)."""
import asyncio

from sqlalchemy import select

from .db import SessionLocal, create_all
from .models import Lesson, Module, Order, QuizQuestion

FREE = ["Что такое ELI_S team и как здесь зарабатывают", "Как устроен диалог с клиентом", "Один день из жизни инвайтера и переписчика"]
COMMON = ["Как устроен диалог", "Боль клиента простыми словами", "Возражения: «дорого» и «подумаю»"]
MSG = ["Первое сообщение", "Как не слить диалог на 2-м сообщении", "Квалификация в переписке", "Прогрев: не торопить клиента"]
QUIZ = [
    ("Клиент первым сообщением спрашивает «сколько стоит?». Что делаешь?", ["Сразу называю цену", "Уточняю, какую задачу он решает", "Отправляю прайс файлом", "Предлагаю скидку"], 1, "Цена без контекста почти всегда звучит дорого."),
    ("Сколько уточняющих вопросов обычно хватает до предложения?", ["1–2 точных вопроса", "Ни одного", "5–7 вопросов", "Чем больше, тем лучше"], 0, "Двух точных вопросов хватает."),
    ("Клиент отвечает коротко: «ок». Что это скорее всего значит?", ["Он готов купить", "Можно отправлять реквизиты", "Интерес падает, нужен вопрос с выбором", "Нужно подождать неделю"], 2, "Вопрос с выбором возвращает участие."),
    ("Какая фраза прогревает, а не давит?", ["Места заканчиваются, решайте сегодня", "Что для вас важнее: скорость или результат?", "Это лучшее предложение на рынке", "Почему вы всё ещё думаете?"], 1, "Вопрос о приоритетах помогает назвать ценность."),
    ("Когда уместно назвать цену?", ["В первом сообщении", "После третьего напоминания", "Никогда, пусть спросит сам", "Когда клиент понял, какую задачу решит"], 3, "Цена звучит спокойно рядом с понятной пользой."),
]


async def main() -> None:
    await create_all()
    async with SessionLocal() as s:
        if await s.scalar(select(Module.id).limit(1)):
            print("данные уже есть")
            return
        free = Module(title="Знакомство", position=0, is_free=True)
        common = Module(title="Общий блок", position=1)
        msg = Module(title="Переписка", position=2, direction="msg")
        s.add_all([free, common, msg])
        await s.flush()
        for i, t in enumerate(FREE):
            s.add(Lesson(module_id=free.id, title=t, position=i, duration_sec=180, published=True))
        for m, titles in ((common, COMMON), (msg, MSG)):
            for i, t in enumerate(titles):
                l = Lesson(module_id=m.id, title=t, position=i, duration_sec=180, published=True, pass_score=1,
                           summary_md=f"## {t}\nКороткий разбор с примерами из реальных диалогов.", chapters=[[0, "Вступление"], [60, "Главное"]])
                s.add(l)
                await s.flush()
                quiz = QUIZ if t.startswith("Прогрев") else QUIZ[:1]
                if t.startswith("Прогрев"):
                    l.pass_score, l.duration_sec = 4, 384
                    l.chapters = [[0, "Зачем нужен прогрев"], [48, "Ошибка: цена в первом ответе"], [121, "Метод двух вопросов"], [205, "Разбор живой переписки"], [318, "Задание к уроку"]]
                for k, (q, o, c, e) in enumerate(quiz):
                    s.add(QuizQuestion(lesson_id=l.id, position=k, text=q, options=o, correct=c, explanation=e))
        s.add_all([
            Order(type="inv", title="Инвайтинг в канал «Ремонт в Минске»", client="Студия ремонта «Квадрат»", rate="18 ₽", unit="за участника",
                  volume="1 500 участников", deadline="до 30 нояб", seats=6, brief="Живые люди из Минска, которые планируют ремонт.",
                  rules=["Только живые аккаунты", "Не больше 40 приглашений в сутки", "Оплата за тех, кто остался через 7 дней"]),
            Order(type="msg", title="Довести заявки до оплаты курса по дизайну", client="Школа дизайна «Форма»", rate="15%", unit="с чека",
                  volume="~60 заявок/мес", deadline="бессрочно", seats=3, brief="Тёплые заявки с вебинара.", rules=["Ответ на заявку в течение 15 минут"]),
        ])
        await s.commit()
        print("готово")


if __name__ == "__main__":
    asyncio.run(main())
