"""Тест на роль: 8 вопросов о склонностях и 2 мини-задачи с верным ответом."""

DIRS = {"inv": "Инвайтинг", "msg": "Переписка", "call": "Звонки", "lead": "Лидген"}
_P = [
    ("Что тебе ближе?", ["Говорить по телефону", "Переписываться", "Искать информацию и контакты", "Находить людей в чатах и звать"]),
    ("Человек не отвечает второй день. Что сделаешь?", ["Позвоню", "Напишу с вопросом", "Найду другого", "Напишу в общий чат, где он есть"]),
    ("Что приятнее сделать за день?", ["Закрыть сделку в разговоре", "Довести переписку до оплаты", "Собрать таблицу из 100 контактов", "Привести 50 человек в канал"]),
    ("Как ты относишься к отказам?", ["Нормально, это часть работы", "Лучше письменно, есть время подумать", "Предпочитаю работу без лишнего общения", "Норм, если их много и быстро"]),
    ("Где тебе проще сосредоточиться?", ["В разговоре", "В тексте", "В таблицах", "В потоке однотипных действий"]),
    ("Что из этого ты уже делал?", ["Продавал или работал в колл-центре", "Отвечал клиентам в соцсетях", "Искал информацию для других", "Вёл или продвигал канал, чат"]),
    ("Какой темп тебе нравится?", ["Быстрый и живой", "Спокойный, но с результатом", "Размеренный, сам решаю", "Много коротких задач подряд"]),
    ("Что для тебя важнее в работе?", ["Общаться с людьми", "Убеждать словами", "Точность и порядок", "Видеть, как растут цифры"]),
]
_ORDER = ["call", "msg", "lead", "inv"]  # вариант N в вопросах 1–8 соответствует направлению _ORDER[N]
TASKS = [
    ("Задача: из 200 приглашённых через 7 дней в канале осталось 170. Какое удержание?", ["75%", "80%", "85%", "90%"], 2),
    ("Задача: клиент пишет «дорого». Какой ответ лучше?", ["«Дешевле не найдёте»", "«Хорошо, сделаю скидку»", "«Понимаю. С чем сравниваете?»", "«Тогда до свидания»"], 2),
]


def questions() -> list[dict]:
    qs = [{"text": t, "options": o, "kind": "fit"} for t, o in _P]
    qs += [{"text": t, "options": o, "kind": "task"} for t, o, _ in TASKS]
    return qs


def score(answers: list[int]) -> dict:
    total = len(_P) + len(TASKS)
    if len(answers) != total or any(not isinstance(a, int) or not 0 <= a < 4 for a in answers):
        raise ValueError(f"нужно {total} ответов, каждый от 0 до 3")
    scores = {d: 0 for d in DIRS}
    for a in answers[: len(_P)]:
        scores[_ORDER[a]] += 1
    smart = sum(1 for (_, _, ok), a in zip(TASKS, answers[len(_P):]) if a == ok)
    top = max(_ORDER, key=lambda d: scores[d])  # при равенстве — первый по порядку
    return {"scores": scores, "top": top, "smart": smart, "fit_total": len(_P)}
